create table if not exists public.marketing_channels (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(name) between 2 and 80),
  slug text not null unique check (slug ~ '^[a-z0-9][a-z0-9_-]{2,39}$'),
  whatsapp_url text not null check (
    whatsapp_url ~ '^https://(chat\.whatsapp\.com|whatsapp\.com/channel)/[A-Za-z0-9_-]+'
  ),
  notes text not null default '' check (char_length(notes) <= 500),
  is_active boolean not null default true,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.marketing_campaigns (
  id uuid primary key default gen_random_uuid(),
  channel_id uuid not null references public.marketing_channels(id) on delete cascade,
  entity_type text not null check (entity_type in ('site', 'place', 'driver', 'feature')),
  entity_id uuid,
  template_key text not null check (
    template_key in (
      'new_place',
      'new_driver',
      'weekly_roundup',
      'merchant_invite',
      'driver_invite',
      'missing_service',
      'data_correction',
      'local_ambassadors',
      'general_site'
    )
  ),
  campaign_code text not null unique default
    substring(replace(gen_random_uuid()::text, '-', '') from 1 for 16),
  status text not null default 'draft' check (status in ('draft', 'published')),
  payload jsonb not null default '{}'::jsonb check (
    jsonb_typeof(payload) = 'object'
    and pg_column_size(payload) <= 4096
  ),
  created_by uuid references auth.users(id) on delete set null,
  last_published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (
    (entity_type in ('place', 'driver') and entity_id is not null)
    or (entity_type in ('site', 'feature') and entity_id is null)
  )
);

create unique index if not exists marketing_campaign_entity_channel_idx
  on public.marketing_campaigns (
    channel_id,
    entity_type,
    coalesce(entity_id, '00000000-0000-0000-0000-000000000000'::uuid),
    template_key
  );
create index if not exists marketing_campaigns_channel_status_idx
  on public.marketing_campaigns (channel_id, status, updated_at desc);
create index if not exists marketing_campaigns_code_idx
  on public.marketing_campaigns (campaign_code);

create table if not exists public.marketing_publications (
  id bigint generated by default as identity primary key,
  campaign_id uuid not null references public.marketing_campaigns(id) on delete cascade,
  published_by uuid references auth.users(id) on delete set null,
  published_at timestamptz not null default now()
);

create index if not exists marketing_publications_campaign_date_idx
  on public.marketing_publications (campaign_id, published_at desc);

alter table public.marketing_channels enable row level security;
alter table public.marketing_campaigns enable row level security;
alter table public.marketing_publications enable row level security;

revoke all on public.marketing_channels from public, anon, authenticated;
