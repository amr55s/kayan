create or replace function public.record_site_analytics_v2(
  p_visitor_hash text,
  p_event_name text,
  p_target_type text,
  p_target_key text,
  p_route text,
  p_campaign_key text default '',
  p_limit integer default 120
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_attempts integer;
  v_campaign_key text;
begin
  if coalesce(auth.jwt() ->> 'role', '') <> 'service_role' then
    raise exception 'service_role_required';
  end if;

  v_campaign_key := coalesce(p_campaign_key, '');
  if p_visitor_hash !~ '^[a-f0-9]{64}$'
     or p_event_name not in (
       'page_view', 'place_open', 'driver_open', 'phone_click',
       'whatsapp_click', 'group_click', 'telegram_click', 'map_click',
       'share_click', 'marketing_share_click', 'card_download', 'guide_open',
       'favorite_click', 'upvote_click', 'search_use', 'category_select',
       'join_open', 'feedback_open', 'add_listing_open',
       'driver_signup_open', 'support_click'
     )
     or p_target_type not in ('site', 'place', 'driver', 'category', 'feature')
     or char_length(p_target_key) > 64
     or v_campaign_key !~ '^[a-zA-Z0-9_-]{0,64}$'
     or p_route !~ '^/[a-zA-Z0-9/_-]*$'
     or char_length(p_route) > 120
     or p_limit not between 1 and 500 then
    raise exception 'invalid_analytics_input';
  end if;

  insert into public.analytics_rate_limits (
    visitor_hash, window_started_at, attempts, updated_at
  )
  values (p_visitor_hash, now(), 1, now())
  on conflict (visitor_hash) do update
  set window_started_at = case
        when analytics_rate_limits.window_started_at <= now() - interval '1 hour'
          then now()
        else analytics_rate_limits.window_started_at
      end,
      attempts = case
        when analytics_rate_limits.window_started_at <= now() - interval '1 hour'
          then 1
        else analytics_rate_limits.attempts + 1
      end,
      updated_at = now()
  returning attempts into v_attempts;
  if v_attempts > p_limit then return false; end if;

  insert into public.analytics_daily_visitors (event_date, visitor_hash, last_seen_at)
  values (current_date, p_visitor_hash, now())
  on conflict (event_date, visitor_hash) do update
  set last_seen_at = now();

  insert into public.analytics_daily_events (
    event_date,
    event_name,
    target_type,
    target_key,
    route,
    campaign_key,
    events,
    updated_at
  )
  values (
    current_date,
    p_event_name,
    p_target_type,
    p_target_key,
    p_route,
    v_campaign_key,
    1,
    now()
  )
  on conflict (
    event_date,
    event_name,
    target_type,
    target_key,
    route,
    campaign_key
  )
  do update set
    events = analytics_daily_events.events + 1,
    updated_at = now();

  if pg_catalog.random() < 0.01 then
    delete from public.analytics_rate_limits
    where updated_at < now() - interval '2 hours';
    delete from public.analytics_daily_visitors
    where event_date < current_date - 30;
    delete from public.analytics_daily_events
    where event_date < current_date - 180;
  end if;
  return true;
end;
$$;

revoke all on function public.record_site_analytics_v2(
  text, text, text, text, text, text, integer
) from public, anon, authenticated;
grant execute on function public.record_site_analytics_v2(
  text, text, text, text, text, text, integer
) to service_role;

